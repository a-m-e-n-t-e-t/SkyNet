def serialize_value(value: Any, indent: int = 0) -> str:
    """YAML-сериализация."""
    pad = "  " * indent
    pad_child = "  " * (indent + 1)
    
    if isinstance(value, str):
        if any(c in value for c in [":", "#", "\n", "{", "}", "[", "]", ",", "&", "*", "?", "|", "<", ">", "=", "%", "@", "`", '"', "'"]):
            escaped = value.replace("'", "''")
            return f"'{escaped}'"
        return value
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, type(None)):
        return "null"
    if isinstance(value, list):
        if not value:
            return "[]"
        items = []
        for v in value:
            items.append(f"{pad_child}- {serialize_value(v, indent + 1)}")
        return "\n" + "\n".join(items)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = []
        for k, v in value.items():
            if isinstance(v, dict):
                if v:
                    lines.append(f"{pad_child}{k}:")
                    sub = serialize_value(v, indent + 2)
                    for line in sub.split("\n"):
                        if line:
                            lines.append(pad_child + "  " + line)
                else:
                    lines.append(f"{pad_child}{k}: {{}}")
            elif isinstance(v, list):
                if v:
                    lines.append(f"{pad_child}{k}:")
                    sub = serialize_value(v, indent + 1)
                    for line in sub.split("\n"):
                        if line:
                            lines.append(pad_child + line if not line.startswith(" ") else pad_child + "  " + line.lstrip())
                else:
                    lines.append(f"{pad_child}{k}: []")
            else:
                lines.append(f"{pad_child}{k}: {serialize_value(v, indent + 1)}")
        return "\n" + "\n".join(lines)
    return "null"


def read_yaml(text: str) -> tuple[str, str, int]:
    if not text.startswith("---"):
        return "", text, 3
    end_match = re.search(r"\n---\s*\n", text[3:])
    if not end_match:
        return "", text, 3
    end_pos = 3 + end_match.start()
    return text[3:end_pos], text[3 + end_match.end():], end_pos


def get_subsystem(yaml_text: str) -> str:
    m = re.search(r"^подсистема:\s*(.+?)\s*$", yaml_text, re.MULTILINE)
    return m.group(1).strip() if m else ""


def update_yaml_field(yaml_text: str, field: str, new_value: Any) -> str:
    """Обновить одно top-level поле. Если оно уже есть — заменить значение полностью
    (включая под-поля до следующего top-level поля).
    """
    # Найти блок поля (от `field:` до следующего top-level поля или конца)
    pattern = rf"^{re.escape(field)}:\s*\n(?:.*?\n)*?(?=^[A-Za-zА-Яа-яЁё_][\wА-Яа-яЁё-]*:|\Z)"
    m = re.search(pattern, yaml_text, re.MULTILINE | re.DOTALL)
    
    serialized = serialize_value(new_value)
    replacement = f"{field}: {serialized}"
    
    if m:
        # Заменить существующий блок
        return yaml_text[:m.start()] + replacement + "\n" + yaml_text[m.end():]
    else:
        # Добавить новое поле (после id: или в начало)
        # Найти `id:` и добавить после него
        id_pattern = r"^(id:[^\n]*\n)"
        if re.search(id_pattern, yaml_text, re.MULTILINE):
            return re.sub(id_pattern, rf"\1{replacement}\n", yaml_text, count=1, flags=re.MULTILINE)
        else:
            return replacement + "\n" + yaml_text


def update_izdelie_file(filepath: Path, canon: dict[str, Any]) -> tuple[bool, list[str]]:
    """Обновить файл изделия канон-данными."""
    text = filepath.read_text(encoding="utf-8")
    yaml_text, body_text, end_pos = read_yaml(text)
    if not yaml_text:
        return False, []
    
    new_yaml = yaml_text
    updated_fields = []
    
    # Обновить каждое поле из canon
    for field, value in canon.items():
        old_value_match = re.search(rf"^{re.escape(field)}:.*?(?=^[A-Za-zА-Яа-яЁё_][\wА-Яа-яЁё-]*:|\Z)", 
                                     new_yaml, re.MULTILINE | re.DOTALL)
        if not old_value_match:
            continue  # поля нет в файле
        
        serialized = serialize_value(value)
        replacement = f"{field}: {serialized}"
        new_yaml = new_yaml[:old_value_match.start()] + replacement + "\n" + new_yaml[old_value_match.end():]
        updated_fields.append(field)
    
    # Обновить дату
    new_yaml = re.sub(
        r"^дата_обновления:\s*\d{4}-\d{2}-\d{2}\s*$",
        f"дата_обновления: {TODAY}",
        new_yaml,
        count=1,
        flags=re.MULTILINE,
    )
    
    if new_yaml == yaml_text:
        return False, []
    
    new_text = "---\n" + new_yaml + body_text
    filepath.write_text(new_text, encoding="utf-8")
    return True, updated_fields


def update_tech_file(filepath: Path, canon: dict[str, Any]) -> tuple[bool, list[str]]:
    """Обновить файл технологии канон-данными."""
    return update_izdelie_file(filepath, canon)


