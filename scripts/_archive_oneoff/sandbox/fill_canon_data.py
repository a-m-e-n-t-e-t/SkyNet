def read_yaml_frontmatter(text: str) -> tuple[str, str, str]:
    """Возвращает (yaml_text, body_text, end_pos)."""
    if not text.startswith("---"):
        return "", text, 3
    end_match = re.search(r"\n---\s*\n", text[3:])
    if not end_match:
        return "", text, 3
    end_pos = 3 + end_match.start()
    return text[3:end_pos], text[3 + end_match.end():], end_pos


def get_type_from_yaml(yaml_text: str) -> str:
    """Извлечь тип_модели из YAML."""
    m = re.search(r"^тип_модели:\s*(.+?)\s*$", yaml_text, re.MULTILINE)
    if m:
        return m.group(1).strip()
    return ""


def get_existing_fields(yaml_text: str) -> set[str]:
    """Какие top-level поля уже есть в YAML."""
    fields = set()
    for line in yaml_text.split("\n"):
        if ":" in line and not line.startswith(" ") and not line.startswith("#") and not line.startswith("-"):
            field = line.split(":", 1)[0].strip()
            fields.add(field)
    return fields


def serialize_value(value: Any, indent: int = 0) -> str:
    """Преобразовать Python-значение в YAML-строку.
    
    indent — уровень отступа (число пробелов).
    Возвращает строку БЕЗ ведущего поля: (это добавит вызывающий код).
    """
    pad = "  " * indent
    pad_child = "  " * (indent + 1)
    
    if isinstance(value, str):
        # Если строка содержит специальные символы — добавить кавычки
        if any(c in value for c in [":", "#", "\n", "{", "}", "[", "]", ",", "&", "*", "?", "|", "<", ">", "=", "%", "@", "`", '"', "'"]):
            escaped = value.replace("'", "''")
            return f"'{escaped}'"
        return value
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, type(None)):
        return "null"
    if isinstance(value, list):
        if not value:
            return "[]"
        items = []
        for v in value:
            if isinstance(v, (dict, list)) and v:
                # Сложный элемент
                items.append(f"{pad_child}- ")
                # Рекурсивно сериализовать
                sub = serialize_value(v, indent + 2)
                # Добавить отступ к каждой строке
                for line in sub.split("\n"):
                    items.append(pad_child + "  " + line + "\n")
            else:
                items.append(f"{pad_child}- {serialize_value(v, indent + 1)}")
        return "\n" + "\n".join(items)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = []
        for k, v in value.items():
            if isinstance(v, dict):
                if v:
                    lines.append(f"{pad_child}{k}:")
                    sub = serialize_value(v, indent + 2)
                    # Добавить отступ к каждой строке
                    for line in sub.split("\n"):
                        if line:
                            lines.append(pad_child + "  " + line)
                else:
                    lines.append(f"{pad_child}{k}: {{}}")
            elif isinstance(v, list):
                if v:
                    lines.append(f"{pad_child}{k}:")
                    sub = serialize_value(v, indent + 1)
                    for line in sub.split("\n"):
                        if line:
                            lines.append(pad_child + line if not line.startswith(" ") else pad_child + "  " + line.lstrip())
                else:
                    lines.append(f"{pad_child}{k}: []")
            else:
                lines.append(f"{pad_child}{k}: {serialize_value(v, indent + 1)}")
        return "\n" + "\n".join(lines)
    return "null"


def fill_model_file(filepath: Path) -> tuple[bool, list[str]]:
    """Заполнить структурные поля канон-данными."""
    text = filepath.read_text(encoding="utf-8")
    yaml_text, body_text, end_pos = read_yaml_frontmatter(text)
    if not yaml_text:
        return False, []
    
    model_type = get_type_from_yaml(yaml_text)
    existing_fields = get_existing_fields(yaml_text)
    
    # Получить канон-данные: сначала специфичные для модели, потом по типу, потом общие
    canon_data = dict(CANON_COMMON)
    type_data = CANON_BY_TYPE.get(model_type, {})
    canon_data.update(type_data)
    model_specific = CANON_BY_MODEL.get(filepath.name, {})
    canon_data.update(model_specific)
    
    # Структурные поля для заполнения
    STRUCTURAL_FIELDS = [
        "требования_выживаемости",
        "маскировка_инфильтратора",
        "тактико_технические_характеристики",
        "защита_от_собственной_радиации",
        "кибербезопасность",
        "эмс_внутренняя",
        "компоновка_изделий",
        "трассировка_соединителей",
        "программное_обеспечение",
        "единая_эми_стратегия",
        "единая_герметичность",
        "сертификация_модели_целого",
        "журнал_экземпляра",
        "утилизация_после_120_лет",
        "экипаж_оператор",
        "промышленная_база",
        "alice_specs",
        "original_improved",
    ]
    
    # Заменить placeholder [] на канон-данные
    new_yaml = yaml_text
    filled_fields = []
    
    for field in STRUCTURAL_FIELDS:
        if field not in existing_fields:
            continue  # нет такого поля — пропускаем
        
        canon_value = canon_data.get(field)
        if canon_value is None:
            continue  # нет канон-данных — оставляем []
        
        # Если текущее значение = [] (placeholder) — заменить
        # Найти строку field: [] и заменить на field: <canon value>
        pattern = rf"^{re.escape(field)}:\s*\[\]\s*$"
        if re.search(pattern, new_yaml, re.MULTILINE):
            serialized = serialize_value(canon_value)
            replacement = f"{field}: {serialized}"
            new_yaml = re.sub(pattern, replacement, new_yaml, count=1, flags=re.MULTILINE)
            filled_fields.append(field)
    
    # Обновить дату
    new_yaml = re.sub(
        r"^дата_обновления:\s*\d{4}-\d{2}-\d{2}\s*$",
        f"дата_обновления: {TODAY}",
        new_yaml,
        count=1,
        flags=re.MULTILINE,
    )
    
    if new_yaml == yaml_text:
        return False, []
    
    new_text = "---\n" + new_yaml + text[end_pos:]
    filepath.write_text(new_text, encoding="utf-8")
    return True, filled_fields


def main():
    print("=== SkyNet — Fill structural fields with canon data ===")
    print()
    
    total = 0
    updated = 0
    total_fields_filled = 0
    
    for f in sorted(MODELS_DIR.glob("*.md")):
        if f.name.startswith("_"):
            continue
        total += 1
        changed, fields = fill_model_file(f)
        if changed:
            updated += 1
            total_fields_filled += len(fields)
            print(f"  ✓ {f.name:30s} +{len(fields)} полей с канон-данными")
        else:
            print(f"    {f.name:30s} (no change)")
    
    print()
    print(f"=== Сводка ===")
    print(f"  Всего моделей: {total}")
    print(f"  Обновлено с канон-данными: {updated}")
    print(f"  Полей заполнено канон-данными: {total_fields_filled}")


if __name__ == "__main__":
    main()
