TPL_RE = re.compile(r'## Описание\s*\n\s*\n.*?(?=## Технические характеристики)', re.S)

def fix_one(f):
    txt = io.open(f['path'], encoding='utf-8').read()
    fid = f['path'].split('/')[-2]
    # габариты
    txt = re.sub(r'габариты_mm:\s*\n\s*l:\s*\S+\s*\n\s*w:\s*\S+\s*\n\s*h:\s*\S+',
                 f'габариты_mm:\n    l: {f["l"]}\n    w: {f["w"]}\n    h: {f["h"]}', txt, count=1)
    # материал
    txt = re.sub(r'(материалы_частей:\s*\n\s*- часть:\s*\S+\s*\n\s*материал:\s*)\S+',
                 lambda m: m.group(1) + f['mat'], txt, count=1)
    # источник
    if 'источник_url:' not in txt:
        txt = txt.replace('источник: web_search\n',
                          f'источник: web_search\nисточник_url: {f["url"]}\nисточник_дата: 2026-11-05\n', 1)
    txt = txt.replace('источник_разбора: канон', 'источник_разбора: веб-верификация')
    # дополнительные
    if 'дополнительные: {}' in txt:
        txt = txt.replace('дополнительные: {}', 'дополнительные:\n' + f['add'].rstrip('\n'), 1)
    # дата
    txt = re.sub(r'дата_обновления:\s*\S+', 'дата_обновления: 2026-11-05', txt, count=1)
    # описание
    parent = re.search(r'(Родитель: `[^`]+`[^\n]*\n)', txt)
    parent_line = parent.group(1) if parent else ''
    txt = TPL_RE.sub('## Описание\n\n' + f['desc'] + '\n\n' + parent_line + '\n', txt, count=1)
    # таблица
    dims = f'{f["l"]}×{f["w"]}×{f["h"]}'
    txt = re.sub(r'\| габариты \(Д×Ш×В\) \| [^|]+\| [^|]+\| [^|]+\|',
                 f'| габариты (Д×Ш×В) | {dims} | mm | {f["dim_src"]} |', txt, count=1)
    txt = re.sub(r'\| материал \| [^|]+\| [^|]+\| [^|]+\|',
                 f'| материал | {f["mat"]} | — | {f["mat_src"]} |', txt, count=1)
    # ссылка на материал
    txt = re.sub(r'- `[a-zа-яё0-9_₃₂²₄-]+` → \[[^\]]+\]\([^)]+\)',
                 f'- `{f["mat"]}` → [`{f["mat"]}.md`](../../../../материалы/{f["mat"]}.md)', txt, count=1)
    io.open(f['path'], 'w', encoding='utf-8').write(txt)
    return f'{fid}: OK ({dims}, {f["mat"]})'

