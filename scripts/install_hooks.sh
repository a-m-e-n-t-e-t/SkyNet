#!/usr/bin/env bash
# scripts/install_hooks.sh — установка локального pre-commit hook для SkyNet.
#
# Проблема, которую решает:
#   GitHub Actions pre-commit-checks.yml ловит ошибки с задержкой 5-10 минут
#   после push. Локальный .git/hooks/pre-commit запускается ДО git commit,
#   блокируя плохой коммит на этапе набора текста.
#
# v9.37 — добавлено в рамках A1 (локальная автоматизация).
#
# Установка:
#   bash scripts/install_hooks.sh
#
# Удаление:
#   rm .git/hooks/pre-commit

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HOOK_PATH="$REPO_ROOT/.git/hooks/pre-commit"

if [ ! -d "$REPO_ROOT/.git" ]; then
    echo "ERROR: $REPO_ROOT/.git not found — not a git repository"
    exit 1
fi

mkdir -p "$REPO_ROOT/.git/hooks"

cat > "$HOOK_PATH" <<'EOF'
#!/usr/bin/env bash
# Auto-generated by scripts/install_hooks.sh (v9.37)
# Запускает scripts/pre-commit-hook.py перед каждым git commit.
# При FAIL — блокирует коммит (exit 1), пока ошибки не исправлены.

set -e
cd "$(git rev-parse --show-toplevel)"

# Pre-commit только для коммитов, затрагивающих данные/скрипты.
# Документация и диалоги не должны запускать полный pre-commit (path-filter).
STAGED=$(git diff --cached --name-only --diff-filter=ACM)
if ! echo "$STAGED" | grep -qE '^(реальные данные/|фантастические данные/|scripts/|требования_к_ии/|graphs/)'; then
    echo "[pre-commit] No data/scripts changes — skipping F-metrics check."
    exit 0
fi

echo "[pre-commit] Running SkyNet pre-commit-hook.py..."
if python3 scripts/pre-commit-hook.py; then
    echo "[pre-commit] ✓ All checks PASSED"
    # Auto-stage regenerated graphs/ if pre-commit-hook updated them
    git add graphs/ 2>/dev/null || true
    exit 0
else
    echo "[pre-commit] ✗ FAILED — commit blocked. Fix issues above and retry."
    echo "[pre-commit] To bypass (NOT recommended): git commit --no-verify"
    exit 1
fi
EOF

chmod +x "$HOOK_PATH"
echo "✓ Installed pre-commit hook → $HOOK_PATH"
echo ""
echo "Hook will run on every 'git commit' touching:"
echo "  - реальные данные/**"
echo "  - фантастические данные/**"
echo "  - scripts/**"
echo "  - требования_к_ии/**"
echo "  - graphs/**"
echo ""
echo "To uninstall: rm $HOOK_PATH"
echo "To bypass:    git commit --no-verify (NOT recommended)"
