def update_all_parts():
    """Перегенерировать все часть_* файлы с реальными данными."""
    updated = 0
    not_found_subtypes = set()
    
    for f in sorted(IZDELIYA_DIR.rglob("_index.md")):
        data, yaml_text, body = read_yaml_frontmatter(f)
        if not data or 'id' not in data:
            continue
        part_id = data['id']
        if not part_id.startswith('часть_'):
            continue
        
        # Извлечь данные
        parent_id = data.get('родитель', '')
        subsystem = data.get('подсистема', 'прочее')
        subtype = data.get('подтип', 'прочее')
        basic = data.get('основные', {})
        if not isinstance(basic, dict):
            basic = {}
        mass_kg = basic.get('масса_kg', 0.1)
        share = basic.get('доля_массы_родителя', 0.1)
        
        # Проверить есть ли данные для подтипа
        if subtype not in PART_DATA:
            not_found_subtypes.add(subtype)
        
        # Сгенерировать реальное содержимое
        content = generate_real_part_content(part_id, parent_id, subsystem, subtype, mass_kg, share)
        write_atomic(f, content)  # v9.37: atomic write
        updated += 1
    
    return updated, not_found_subtypes


